// Builds web/bin/clip.mjs, the committed bundle a session runs with plain
// `node`: the clipper and its dependencies in one file. The build is
// deterministic, so the web gate rebuilds it and diffs it against the commit.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'

await build({
  entryPoints: [fileURLToPath(new URL('src/cli.ts', import.meta.url))],
  outfile: fileURLToPath(new URL('../bin/clip.mjs', import.meta.url)),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  // Whitespace and syntax only: identifiers stay readable in a bug's stack trace.
  minifyWhitespace: true,
  minifySyntax: true,
  legalComments: 'eof',
  banner: {
    js: [
      '#!/usr/bin/env node',
      '// Generated by web/clipper/build.mjs from web/clipper/src; do not edit. Rebuild: cd web/clipper && npm run build',
      // Defuddle is CommonJS: its require() calls need a require in an ES module.
      "import { createRequire as __clipCreateRequire } from 'node:module'; const require = __clipCreateRequire(import.meta.url);",
    ].join('\n'),
  },
  logLevel: 'warning',
})
