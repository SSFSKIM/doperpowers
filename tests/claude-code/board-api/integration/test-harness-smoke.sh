#!/usr/bin/env bash
# test-harness-smoke.sh — the A2 integration tier's own smoke test: prove the
# harness brings up a REAL A1 board-service, and that a consumer repo bound to
# it with .doperpowers/board.json round-trips a ticket through the toolkit's
# own verbs (board-register.sh -> board-list.sh) over an actual socket.
#
# Every other test in board-api/ drives a fixture mock; this one drives the
# service, so it is the only place a payload the mock happily accepts can be
# caught being wrong.
#
# Gated: with no arkho checkout (or no container runtime for the scratch
# Postgres) the harness prints its reason and exits 77, and this file skips
# LOUDLY and exits 0. It never fails on a machine that cannot host the service.
. "$(dirname "$0")/../helpers.sh"

HERE="$(cd "$(dirname "$0")" && pwd)"
H="$HERE/harness.sh"

rc=0
"$H" start || rc=$?
if [ "$rc" -eq 77 ]; then
  echo "SKIP $(basename "$0") — prerequisites missing (reason above); the tier is gated, not failed"
  exit 0
elif [ "$rc" -ne 0 ]; then
  echo "FAIL $(basename "$0") — harness start failed (exit $rc)"
  exit 1
fi
trap '"$H" stop' EXIT

# shellcheck source=/dev/null  # generated by harness.sh start, above
. "$HERE/.harness/env.sh"

AUTOMATION_TOKEN="$(awk -F= '/^BOARD_AUTOMATION_TOKEN=/{print $2}' "$BOARD_CREDENTIALS_FILE")"

t "healthz is green" '"ok":true' curl -s "$BOARD_API_URL/healthz"
t "the minted automation principal is admitted" "[" \
  curl -s -H "authorization: Bearer $AUTOMATION_TOKEN" "$BOARD_API_URL/tickets"
t "an unminted token is refused" '"code":"unauthenticated"' \
  curl -s -H "authorization: Bearer not-a-real-token" "$BOARD_API_URL/tickets"

# ---- the end-to-end: a consumer repo bound to the local instance -----------
# A real checkout with a real binding file, driven through the real entry
# points — not the python client directly. This is what a repo adopting A2
# actually looks like.
REPO="$(mkrepo)"
mkdir -p "$REPO/.doperpowers"
printf '{"binding": "api", "url": "%s"}\n' "$BOARD_API_URL" >"$REPO/.doperpowers/board.json"

BODY="$REPO/spec.md"
cat >"$BODY" <<'MD'
## Problem & intent

The integration harness must prove a ticket survives the whole path: the
toolkit's register verb, the service's birth legality, Postgres, and the
list verb reading it back.

## Success criteria

The registered ticket comes back from board-list.sh in its birth state.
MD

in_repo() { (cd "$REPO" && "$@"); }

# Captured rather than asserted inline, because the id it prints is the input
# to every assertion after it.
reg_out="$(in_repo "$SCRIPTS/board-register.sh" \
  "harness smoke ticket" enhancement P2 --body-file "$BODY" 2>&1)" || true
t "register reports the new ticket and its API url" "$BOARD_API_URL/tickets/" \
  printf '%s\n' "$reg_out"

tid="$(printf '%s\n' "$reg_out" | awk 'END{print $1}')"
# State AND priority AND title in one row: a register that silently dropped the
# body would have been demoted to needs-info, and one that dropped the priority
# would print `-`. board-list.sh's API-mode row is `#<id> <state> <prio> <title>`.
t "the ticket lands on the board in its birth state" \
  "#$tid ready-for-implementer P2 harness smoke ticket" \
  in_repo "$SCRIPTS/board-list.sh"
t "the state filter reaches it too" "#$tid " \
  in_repo "$SCRIPTS/board-list.sh" ready-for-implementer
nt "a foreign state filter does not" "#$tid " \
  in_repo "$SCRIPTS/board-list.sh" "done"

finish
