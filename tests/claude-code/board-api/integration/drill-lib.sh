#!/usr/bin/env bash
# drill-lib.sh — scaffolding shared by the six A2 integration drills.
#
# Every drill in this directory drives the REAL toolkit against the REAL A1
# board-service that harness.sh stands up (scratch Postgres, scratch
# principals, 127.0.0.1:8917). This file owns the four things all six repeat:
#
#   drill_start   boot the harness or SKIP the drill (the exit-77 contract),
#                 pin HOME / DAEMON_HOME / PATH into a scratch world, and
#                 arrange teardown so a drill leaves zero residue.
#   api           one curl against the service as a named principal — used to
#                 OBSERVE (feeds, listings) and, where a drill says so, to
#                 SEED a fixture through a real route.
#   sql           psql inside the scratch container. SETUP ONLY, and only for
#                 state that is not itself under test (aging a lease so the
#                 service's own reconciler reclaims on its own authority).
#                 Nothing is ever ASSERTED through it: an assertion that reads
#                 the database proves the database, not the toolkit.
#   sminos_stub    one scripted stand-in for the sminos CLI, covering the verbs
#                 the pipeline calls: spawn / resume / sync / retire / migrate.
#                 Workers are sminos-spawned Claude sessions in production; a
#                 drill spawns none. The stub emits the GENUINE banner shape
#                 (the dispatcher parses the uuid out of it), writes the prompt
#                 into a transcript file (delivery IS the transcript write,
#                 which is what the relay's sentinel gate later reads), and
#                 records its argv + BOARD_* env.
#
# ISOLATION: one harness instance per drill (harness.sh pins a container name
# and a port, so there is one at a time per checkout anyway). Each drill boots
# a fresh scratch database and tears it down on the way out, which costs ~10s
# and buys total independence — any drill runs alone, in any order, and no
# drill can inherit another's board. Per-drill SQL truncation would have been
# cheaper and would have coupled every drill to the schema's table list.
#
# shellcheck disable=SC2034  # this is a library: its callers consume the vars
. "$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/helpers.sh"

DRILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HARNESS="$DRILL_DIR/harness.sh"
PG_CONTAINER="${A2_PG_CONTAINER:-a2-harness-pg}"

# The one skip line the whole tier shares: the harness prints WHY on stderr and
# answers 77, and a drill that cannot run is skipped LOUDLY rather than failed.
drill_start() {
  local rc=0
  "$HARNESS" start || rc=$?
  if [ "$rc" -eq 77 ]; then
    # 77, NOT 0. A skip that exits 0 is indistinguishable from a pass to
    # anything counting exit statuses, so a tier that silently stopped running
    # — a stopped Docker daemon, an unset ARKHO_DIR — reads as a green tier.
    # The harness's own contract is 77 for "prerequisite missing"; it is
    # propagated rather than swallowed.
    echo "SKIP $(basename "$0") — prerequisites missing (reason above); the tier is gated, not failed (exit 77)"
    exit 77
  elif [ "$rc" -ne 0 ]; then
    echo "FAIL $(basename "$0") — harness start failed (exit $rc)"
    exit 1
  fi
  DRILL_TMP="$(mktemp -d)"
  # INT/TERM as well as EXIT: a Ctrl-C during a drill left the scratch Postgres
  # container and the board-service process running, and the next `start`
  # inherited a half-built world it did not create.
  trap 'drill_stop' EXIT
  trap 'drill_stop; exit 130' INT
  trap 'drill_stop; exit 143' TERM
  # shellcheck source=/dev/null  # generated by harness.sh start, just now
  . "$DRILL_DIR/.harness/env.sh"
  AUTOMATION_TOKEN="$(awk -F= '/^BOARD_AUTOMATION_TOKEN=/{print $2}' "$BOARD_CREDENTIALS_FILE")"
  HUMAN_TOKEN="$(awk -F= '/^BOARD_HUMAN_TOKEN=/{print $2}' "$BOARD_CREDENTIALS_FILE")"

  # The scratch world every drill runs inside. HOME is pinned because the relay
  # and successor paths resolve a session transcript under $HOME/.claude/
  # projects, and DAEMON_HOME because a fall-through would read (and write) the
  # operator's own seat registry.
  DRILL_HOME="$DRILL_TMP/home"
  DAEMON_HOME="$DRILL_TMP/registry"
  SMINOS_STUB="$DRILL_TMP/sminos-stub"
  SMINOS_CLI="$SMINOS_STUB/sminos"
  PROJECTS="$DRILL_HOME/.claude/projects/-drill"
  GH_LOG="$DRILL_TMP/gh-invoked.log"
  SPAWN_LOG="$DRILL_TMP/spawn.log"
  RESUME_LOG="$DRILL_TMP/resume.log"
  SEQ_LOG="$DRILL_TMP/sequence.log"
  DEAD_FILE="$DRILL_TMP/dead-uuids"
  mkdir -p "$DRILL_HOME" "$DAEMON_HOME" "$SMINOS_STUB" "$PROJECTS"
  : >"$GH_LOG"; : >"$SPAWN_LOG"; : >"$RESUME_LOG"; : >"$SEQ_LOG"; : >"$DEAD_FILE"
  _stub_gh
  sminos_stub
  _seed_session_store
}

# The adapter-owned session store, EMPTY — the environment A1's reclaim sweep
# expects to be able to ask, not a fixture any drill asserts against.
#
# It matters that it exists. `storeSaysAlive` (arkho src/reconcile.js) treats a
# FAILED join — the schema absent, revoked, or down — as "the source is
# unavailable, not silent" and grants the run a 120s grace window before any
# reclaim; an empty table is SILENCE, which is what "this plugin feeds no
# session store" (spec acceptance 5) actually means. Without the schema every
# reclaim in this tier would sit out a two-minute hedge against a degraded feed
# that is not what any of these drills is about. Columns are exactly the three
# `reconcile.js` reads, matching the arkho suite's own fixture.
_seed_session_store() {
  sql >/dev/null <<'SQL'
create schema if not exists sessions;
create table if not exists sessions.ccs_sessions
  (project_key text, session_id text, mtime bigint);
SQL
}

drill_stop() {
  local rc=$? d
  "$HARNESS" stop >/dev/null 2>&1 || true
  for d in ${DRILL_REPOS[@]+"${DRILL_REPOS[@]}"}; do rm -rf "$d"; done
  [ -z "${DRILL_TMP:-}" ] || rm -rf "$DRILL_TMP"
  return "$rc"
}
DRILL_REPOS=()

# A `gh` earlier on PATH than any real one, for the WHOLE drill: API mode may
# never reach the GitHub CLI, and a stub that only echoed would be invisible to
# a caller that captures its child's stdout — so it records into a file.
_stub_gh() {
  GH_STUB_DIR="$DRILL_TMP/pathstub"
  mkdir -p "$GH_STUB_DIR"
  cat >"$GH_STUB_DIR/gh" <<'EOF'
#!/usr/bin/env bash
echo "GH INVOKED $*" >> "$GH_STUB_MARKER"
exit 97
EOF
  chmod +x "$GH_STUB_DIR/gh"
  export GH_STUB_MARKER="$GH_LOG"
  PATH="$GH_STUB_DIR:$PATH"
  export PATH
}

# ---- talking to the service ------------------------------------------------
# api <principal> <METHOD> <path> [json-body]
#   principal: automation | human | admin | a raw bearer token
api() {
  local who="$1" method="$2" path="$3" body="${4:-}" tok
  case "$who" in
    automation) tok="$AUTOMATION_TOKEN" ;;
    human) tok="$HUMAN_TOKEN" ;;
    admin) tok="$ADMIN_TOKEN" ;;
    *) tok="$who" ;;
  esac
  if [ -n "$body" ]; then
    curl -s -X "$method" -H "authorization: Bearer $tok" \
      -H 'content-type: application/json' -d "$body" "$BOARD_API_URL$path"
  else
    curl -s -X "$method" -H "authorization: Bearer $tok" "$BOARD_API_URL$path"
  fi
}

# One field out of a JSON document on stdin (dotted path, list index by number).
jget() { T_PATH="$1" python3 -c '
import json, os, sys
cur = json.load(sys.stdin)
for k in os.environ["T_PATH"].split("."):
    cur = cur[int(k)] if isinstance(cur, list) else cur.get(k)
    if cur is None:
        break
print("" if cur is None else cur)'; }

# SETUP ONLY — see the header. Reads SQL on stdin.
sql() {
  docker exec -i -e PGPASSWORD=a2-harness-scratch "$PG_CONTAINER" \
    psql -v ON_ERROR_STOP=1 -h 127.0.0.1 -U postgres -d board_a2_test -qtA
}

# Poll until <cmd> succeeds. A fixed nap against a 1s reconciler is a flake.
wait_until() {  # wait_until <seconds> <what> <cmd...>
  local budget="$1" what="$2"
  shift 2
  local deadline=$((SECONDS + budget))
  while [ "$SECONDS" -lt "$deadline" ]; do
    if "$@" >/dev/null 2>&1; then return 0; fi
    sleep 0.3
  done
  echo "FAIL $(basename "$0") — timed out after ${budget}s waiting for $what" >&2
  return 1
}

