# ---- closing an id ---------------------------------------------------------
# `t`/`nt` match with `grep -qF`, which has no anchor of its own, so an id that
# ENDS what it is printed in is satisfied by every id it prefixes: `owner=17`
# is a substring of `owner=170`, and a drill asserting the first would pass on
# the second — the right verdict for the wrong reason. Two ways to close one,
# and every drill here uses one of them:
#
#   eol         give each line of an emitter's output an explicit terminator,
#               for text this suite does not author (an env dump, a JSON tail).
#   owner_line  the suite's own emitters carry their delimiter in the value.
eol() { sed 's/$/;/' "$@"; }
owner_line() { echo "owner=[$(ticket_owner "$1")]"; }

# ---- the scripted worker sessions -----------------------------------------
# No model call anywhere in this tier. The stub stands in for the sminos layer
# itself, so a drill whose claim IS about that layer would have to say so; none
# of the six is. ONE executable whose first argument selects the verb, exactly
# as the real launcher is called.
sminos_stub() {
  cat >"$SMINOS_CLI" <<EOF
#!/usr/bin/env bash
set -euo pipefail
verb="\${1:-}"; shift || true
case "\$verb" in
migrate) exit 0 ;;
retire)
  echo "retire \$*" >> "$SPAWN_LOG"
  exit 0 ;;
sync)
  # \`absent\` is the only dead answer the sweep accepts (a parked worker is
  # \`noop\`, which is very much alive).
  if grep -qxF "\$1" "$DEAD_FILE" 2>/dev/null; then echo absent; exit 0; fi
  echo live
  exit 0 ;;
spawn) ;;
resume)
  # The real \`sminos resume\` forks the turn and INJECTS the prompt before it
  # blocks; the transcript write below is that injection, and it is what the
  # relay's sentinel gate reads on a later tick.
  if [ "\${1:-}" = "--wait" ]; then shift; fi
  uuid="\$1"; prompt="\$2"
  { echo "RESUME uuid=\$uuid"
    echo "ARGV: \$*"
    echo "DAEMON_TIMEOUT=\${DAEMON_TIMEOUT:-unset}"
    # The run bearer is a SECRET at rest and in flight. The drills assert that it
    # reached the child's environment, which the masked form proves exactly as well as the
    # value does — and a log file carrying it is a credential on disk that outlives
    # the run it belongs to.
    env | grep '^BOARD_' | sed 's/^BOARD_RUN_TOKEN=.*/BOARD_RUN_TOKEN=<set>/' | sort || true
  } >> "$RESUME_LOG"
  echo "resume \$uuid" >> "$SEQ_LOG"
  # Two ways to fail with NOTHING delivered — killed mid-flight, or a resume that
  # returns failure without ever forking a turn. Both must leave the transcript
  # untouched: an injected prompt is a DELIVERY, and the sweep reads it as one.
  [ -z "\${RESUME_DIE_BEFORE:-}" ] || exit 137
  [ -z "\${RESUME_MUST_FAIL:-}" ] || exit 1
  cur="\$(T_P="$DAEMON_HOME/\$uuid.json" python3 -c 'import json,os
try: print(json.load(open(os.environ["T_P"])).get("current") or "")
except Exception: print("")')"
  [ -n "\$cur" ] || cur="\$uuid"
  T_P="$PROJECTS/\$cur.jsonl" T_C="\$prompt" python3 - <<'PYX'
import json, os
with open(os.environ["T_P"], "a") as f:
    f.write(json.dumps({"type": "user",
                        "message": {"role": "user", "content": os.environ["T_C"]}}) + "\n")
PYX
  # Death AFTER the injection but before the caller could ack.
  [ -z "\${RESUME_DIE_AFTER:-}" ] || exit 137
  exit 0 ;;
*) echo "stub sminos: unexpected verb '\$verb'" >&2; exit 2 ;;
esac

# ---- spawn: records the handover, registers a record the way a real no-wait
# spawn does, and echoes the GENUINE banner line — the dispatcher parses the
# uuid out of it.
name="\$1"; task="\$2"; shift 2
cwd=""; wt=""; model=""
while [ \$# -gt 0 ]; do
  case "\$1" in
    --cwd) cwd="\$2"; shift 2 ;;
    --worktree) wt="\$2"; shift 2 ;;
    --model) model="\$2"; shift 2 ;;
    --wait|--no-wait) shift ;;
    *) shift ;;
  esac
done
{ echo "SPAWN name=\$name cwd=\$cwd worktree=\$wt model=\$model"
  # The run bearer is a SECRET at rest and in flight. The drills assert that it
  # reached the child's environment, which the masked form proves exactly as well as the
  # value does — and a log file carrying it is a credential on disk that outlives
  # the run it belongs to.
  env | grep '^BOARD_' | sed 's/^BOARD_RUN_TOKEN=.*/BOARD_RUN_TOKEN=<set>/' | sort || true
  echo "GW settings=[\${DAEMON_CLAUDE_SETTINGS-unset}] effort=[\${DAEMON_CLAUDE_EFFORT-unset}]"
  echo "---- prompt ----"; printf '%s\n' "\$task"; echo "---- end prompt ----"
} >> "$SPAWN_LOG"
echo "spawn \$name" >> "$SEQ_LOG"
printf '%s' "\$task" > "$DRILL_TMP/prompt-\$name.md"
[ -z "\${SPAWN_MUST_FAIL:-}" ] || exit 1
n=\$(cat "$DRILL_TMP/.spawncount" 2>/dev/null || echo 0); n=\$((n + 1))
echo "\$n" > "$DRILL_TMP/.spawncount"
uuid="\$(printf 'aaaa%04d' "\$n")-0000-4000-8000-000000000000"
U="\$uuid" N="\$name" C="\$cwd" T_DH="$DAEMON_HOME" python3 - <<'PY'
import json, os
u = os.environ["U"]
json.dump({"uuid": u, "current": u, "name": os.environ["N"], "cwd": os.environ["C"],
           "status": "working", "updated": "2026-08-10T00:00:00Z"},
          open(os.path.join(os.environ["T_DH"], u + ".json"), "w"))
PY
: > "$PROJECTS/\$uuid.jsonl"
# A REAL transcript line: the delivery proof reads user-role JSONL entries whose
# content is a plain string (a delivered prompt), never the raw bytes — tool
# results ride the same \`user\` type as a content LIST, which is how arbitrary
# text gets back into the file.
T_P="$PROJECTS/\$uuid.jsonl" T_C="\$task" python3 - <<'PYX'
import json, os
with open(os.environ["T_P"], "a") as f:
    f.write(json.dumps({"type": "user",
                        "message": {"role": "user", "content": os.environ["T_C"]}}) + "\n")
PYX
# The spawn is detached and already surviving by the time the banner prints —
# so a crash HERE is a crash between the spawn and the bind.
[ -z "\${SPAWN_KILL_PARENT:-}" ] || kill -9 "\$PPID" 2>/dev/null || true
echo "seat spawned: \$name  [\${uuid%%-*} / \$uuid]  group=drill  status=working  (reply: sminos reply \${uuid%%-*})"
EOF
  chmod +x "$SMINOS_CLI"
}

# Register a session meta for a run that was claimed OUT of band (a drill that
# needs a lease the dispatcher has no flag for). Same shape board-bind.sh
# leaves behind, so the sweep's registry scan reads it identically.
seed_meta() {  # seed_meta <uuid> <ticket> <run> <fence> <bearer> [lane]
  T_DH="$DAEMON_HOME" T_UUID="$1" T_TID="$2" T_RUN="$3" T_FENCE="$4" T_BEARER="$5" \
  T_LANE="${6:-implementer}" python3 - <<'PY'
import json, os
e = os.environ
path = os.path.join(e["T_DH"], e["T_UUID"] + ".json")
m = {"uuid": e["T_UUID"], "current": e["T_UUID"], "name": e["T_TID"] + "-drill",
     "status": "working", "ticket": e["T_TID"], "run_id": int(e["T_RUN"]),
     "fence": int(e["T_FENCE"]), "run_bearer": e["T_BEARER"], "lane": e["T_LANE"],
     "role": "IMPLEMENT", "bind_confirmed": True}
with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
    json.dump(m, f, indent=2)
PY
  : >"$PROJECTS/$1.jsonl"
}

# THE SCRIPTED WORKER'S TURN ENDS. A drill's worker is a meta and a transcript,
# never a session, so nothing in this tier ever takes it out of `working` —
# while in production the next tick's `sminos sync` does, as soon as the turn
# finishes. The distinction is load-bearing downstream: only a MID-TURN owner
# fences a transition (dp#63), so a drill that walks on past a worker's last
# write without ending its turn is asserting against a machine state that
# cannot outlive the worker it describes.
end_turn() {  # end_turn <uuid>
  T_P="$DAEMON_HOME/$1.json" python3 - <<'PY'
import json, os
path = os.environ["T_P"]
with open(path) as f:
    m = json.load(f)
m["status"] = "idle"
mode = os.stat(path).st_mode & 0o777
with os.fdopen(os.open(path, os.O_WRONLY | os.O_TRUNC, mode), "w") as f:
    json.dump(m, f, indent=2)
PY
}

# The registry meta bound to ticket $1, as `uuid<TAB>run<TAB>fence<TAB>bearer`.
# The bearer crosses into a shell variable here and is never echoed — the drills
# that read it hand it straight back to a verb as BOARD_RUN_TOKEN.
meta_of_ticket() {
  T_DH="$DAEMON_HOME" T_TID="$1" python3 - <<'PY'
import glob, json, os
tid = os.environ["T_TID"]
for p in sorted(glob.glob(os.path.join(os.environ["T_DH"], "*.json"))):
    if p.endswith(".reply.json"):
        continue
    try:
        m = json.load(open(p))
    except Exception:
        continue
    if str(m.get("ticket", "")).lstrip("#") == tid:
        print("\t".join([os.path.basename(p)[:-5], str(m.get("run_id", "")),
                         str(m.get("fence", "")), m.get("run_bearer", "") or ""]))
        break
PY
}

# The repo key the drill's bound checkout speaks for, read from the binding file
# the drill is actually running against — so a raw-route helper below cannot
# drift from what the toolkit's own verbs send.
drill_repo_key() {
  python3 -c 'import json, sys; print(json.load(open(sys.argv[1]))["repo"])' \
    "$REPO/.doperpowers/board.json"
}

# One claim through the REAL route, as the dispatchers make it, printing
# `run<TAB>ticket<TAB>fence<TAB>bearer`. Used where a drill needs a knob the
# dispatcher does not expose (a one-minute lease): the claim itself is still
# the product's own route and the server's own pick.
claim_run() {  # claim_run <lane> <nonce> [lease-minutes]
  # The repo comes off the drill's OWN binding file, because that is where the
  # dispatcher this stands in for reads it. /runs/claim is dispatch-shaped: the
  # harness principals are unscoped, and an unscoped credential that names no
  # repo is refused `repo-required` rather than served from the founding one.
  local repo body
  repo="$(drill_repo_key)"
  body="{\"lane\":\"$1\",\"dispatchNonce\":\"$2\",\"repo\":\"$repo\""
  [ -z "${3:-}" ] || body="$body,\"leaseMinutes\":$3"
  api automation POST /runs/claim "$body}" | python3 -c '
import json, sys
o = json.load(sys.stdin)
if not o.get("claimed", True):
    sys.exit("claim answered empty")
print("\t".join(str(o[k]) for k in ("runId", "ticketId", "fence", "bearer")))'
}

# A repo bound to the harness instance — what a consumer adopting A2 looks like.
# The repo KEY is the name the board service knows this checkout by; it defaults
# to the founding repo the schema seeds into `board.repo_state`, which is the one
# every single-repo drill means. A drill that wants a second board passes its own
# and seeds the register row the way the harness seeds principals — the service
# refuses `unknown-repo` on a write into a name it never admitted.
api_repo() {  # api_repo [repo-key]
  local d repo="${1:-doperpowers}"
  d="$(mkrepo)"
  mkdir -p "$d/.doperpowers"
  printf '{"binding":"api","url":"%s","repo":"%s"}\n' "$BOARD_API_URL" "$repo" \
    >"$d/.doperpowers/board.json"
  DRILL_REPOS+=("$d")
  echo "$d"
}

# Run a toolkit verb from inside the bound repo, in the drill's scratch world.
# Extra env (a run bearer, a stub switch) rides in as leading VAR=VALUE words.
in_repo() { (cd "$REPO" && env HOME="$DRILL_HOME" DAEMON_HOME="$DAEMON_HOME" \
  SMINOS_CLI="$SMINOS_CLI" BOARD_CREDENTIALS_FILE="$BOARD_CREDENTIALS_FILE" \
  LOCAL_REPO="$REPO" "$@"); }

# The sweep, one phase at a time, in that same world.
sweep() { in_repo "$SCRIPTS/_sweep_api.sh" "$@"; }

# The per-binding subdirectory a machine-global registry store files under.
# $DAEMON_HOME is shared by every board a machine runs, so `board-claims`,
# `board-suppress` and `surface-locks` each live under one digest of the binding
# (dp#36). Resolved through the toolkit's OWN resolver, in the drill's bound
# checkout, so a drill path cannot disagree with what the product writes — a
# drill that spelled the digest itself would pass on its own arithmetic.
drill_store_dir() {  # drill_store_dir <store name>
  in_repo bash -c ". '$SCRIPTS/_binding.sh'; board_store_dir '$1'"
}
